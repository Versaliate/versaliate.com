const languageSelect = document.querySelector("#language-select");
const descriptionMeta = document.querySelector("#meta-description");
const supportedLanguages = Object.keys(translations);

function normalizeLanguage(language) {
  if (!language) return "en";
  if (language.toLowerCase().startsWith("pt")) return "pt-BR";
  const short = language.slice(0, 2).toLowerCase();
  return supportedLanguages.includes(short) ? short : "en";
}

function applyLanguage(language) {
  const selected = supportedLanguages.includes(language) ? language : "en";
  const dictionary = translations[selected];

  document.documentElement.lang = selected;
  document.title = dictionary.title;
  descriptionMeta.setAttribute("content", dictionary.description);
  languageSelect.value = selected;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const key = element.dataset.i18nAria;
    if (dictionary[key]) element.setAttribute("aria-label", dictionary[key]);
  });

  languageSelect.setAttribute("aria-label", dictionary.languageLabel);
  localStorage.setItem("versaliate-language", selected);
}

const savedLanguage = localStorage.getItem("versaliate-language");
const initialLanguage = savedLanguage || normalizeLanguage(navigator.language);
applyLanguage(initialLanguage);

languageSelect.addEventListener("change", (event) => applyLanguage(event.target.value));

const header = document.querySelector("#site-header");
const updateHeader = () => header.classList.toggle("is-scrolled", window.scrollY > 18);
updateHeader();
window.addEventListener("scroll", updateHeader, { passive: true });

const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
if (prefersReducedMotion || !("IntersectionObserver" in window)) {
  document.querySelectorAll(".reveal").forEach((element) => element.classList.add("is-visible"));
} else {
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    });
  }, { threshold: 0.12 });

  document.querySelectorAll(".reveal").forEach((element) => revealObserver.observe(element));
}
